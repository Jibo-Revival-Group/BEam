'use strict';
var assert = require('assert');
var Runtime = require('../@be/be/skills/agent/runtime');

assert(Runtime.isStop('goodbye'));
assert(Runtime.isStop('good bye'));
assert(Runtime.isStop('Good-bye, Jibo!'));
assert(Runtime.isStop('Okay, goodbye.'));
assert(Runtime.isStop('Bye!'));
assert(!Runtime.isStop('I said goodbye'));
assert(Runtime.isStop('Jibo, stop'));
assert(Runtime.isStop('Jibo stop chatting'));
assert(Runtime.isStop('hey jibo goodbye'));
assert(Runtime.isStop('Hey Jibo, stop.'));
assert(Runtime.isStop('Okay Jibo, bye'));
assert(!Runtime.isStop('Jibo, stop the music'));
assert(!Runtime.isStop('Jibo, why did you stop'));
assert(!Runtime.isStop('Hey Jibo'));
assert(!Runtime.isStop('stop jibo stop'));
